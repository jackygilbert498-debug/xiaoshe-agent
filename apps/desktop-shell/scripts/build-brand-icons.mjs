import { spawnSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const productRoot = resolve(desktopRoot, '..', '..')
const assetsRoot = resolve(productRoot, 'runtime', 'xiaoshe-legacy', 'ui', 'assets')
const tokensPath = resolve(productRoot, 'runtime', 'xiaoshe-legacy', 'ui', 'styles', 'tokens.css')
const formalMarkPath = resolve(assetsRoot, 'snake.svg')
const appSvgPath = resolve(assetsRoot, 'app-icon.svg')
const app512Path = resolve(assetsRoot, 'app-icon-512.png')
const app256Path = resolve(assetsRoot, 'app-icon-256.png')

if (!process.argv.includes('--rasterize')) throw new Error('Usage: build-brand-icons.mjs --rasterize')

const tokens = await readFile(tokensPath, 'utf8')
const colors = [1, 2, 3, 4].map(index => readLightSheen(tokens, index))
const embeddedMark = (await readFile(formalMarkPath)).toString('base64')
const appSvg = `<!-- GENERATED by apps/desktop-shell/scripts/build-brand-icons.mjs.
  Do not draw a second mark here: the embedded image is ui/assets/snake.svg itself. -->
<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512" role="img" aria-label="小蛇">
  <defs>
    <mask id="formal-brand-source" maskUnits="userSpaceOnUse" mask-type="alpha" x="88" y="88" width="336" height="336" style="mask-type:alpha">
      <image href="data:image/svg+xml;base64,${embeddedMark}" x="88" y="88" width="336" height="336" preserveAspectRatio="xMidYMid meet"/>
    </mask>
    <linearGradient id="brand-sheen-app" x1="130" y1="382" x2="382" y2="130" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="${colors[0]}"/>
      <stop offset=".42" stop-color="${colors[1]}"/>
      <stop offset=".72" stop-color="${colors[2]}"/>
      <stop offset="1" stop-color="${colors[3]}"/>
    </linearGradient>
  </defs>
  <rect x="48" y="48" width="416" height="416" rx="94" fill="#ffffff"/>
  <rect x="88" y="88" width="336" height="336" fill="url(#brand-sheen-app)" mask="url(#formal-brand-source)"/>
</svg>
`

await writeFile(appSvgPath, appSvg, 'utf8')
run('rsvg-convert', ['--width', '512', '--height', '512', '--format', 'png', '--output', app512Path, appSvgPath])
run('rsvg-convert', ['--width', '256', '--height', '256', '--format', 'png', '--output', app256Path, appSvgPath])

function readLightSheen(source, index) {
  const match = source.match(new RegExp(`^\\s*--sheen-${index}:\\s*(#[0-9a-f]{6});`, 'imu'))
  if (match === null) throw new Error(`Missing light-theme --sheen-${index} token`)
  return match[1].toLowerCase()
}

function run(command, args) {
  const result = spawnSync(command, args, { stdio: 'inherit' })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) throw new Error(`${command} exited with ${String(result.status)}`)
}
