// Windows-only framing of the approved app tile. No second mark, recoloring,
// or changes to the macOS source. Rasterizers are build-time tools only.
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const desktopRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceRoot = resolve(desktopRoot, '../../runtime/xiaoshe-legacy/ui/assets')
const output = resolve(desktopRoot, 'src/assets')
const args = process.argv.slice(2)
if (!(args.length === 1 && args[0] === '--rasterize') &&
    !(args.length === 3 && args[0] === '--rasterize' && args[1] === '--sharp-module' && args[2]?.trim())) {
  throw new Error('Usage: build-windows-app-icon.mjs --rasterize [--sharp-module <existing module path>]')
}
const sharp = args.length === 3 ? createRequire(import.meta.url)(resolve(args[2])) : undefined
const sha = bytes => createHash('sha256').update(bytes).digest('hex')
const artwork = await readFile(join(sourceRoot, 'app-icon.svg'))
const source = await readFile(join(sourceRoot, 'app-icon-512.png'))
const formal = await readFile(join(sourceRoot, 'snake.svg'))
const artworkText = artwork.toString('utf8')
const embedded = artworkText.match(/data:image\/svg\+xml;base64,([A-Za-z0-9+/=]+)/u)?.[1]
if (!embedded || !Buffer.from(embedded, 'base64').equals(formal)) {
  throw new Error('Approved application artwork is stale: regenerate it from snake.svg first')
}
if (source.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || source.readUInt32BE(16) !== 512 || source.readUInt32BE(20) !== 512) {
  throw new Error('Approved application master must be a 512px PNG')
}

// Windows renders the application icon much smaller than macOS renders a Dock
// tile. Keep the approved white tile and exact formal mark, but give the narrow
// S a Windows-specific 496/432 = 1.148 optical scale. Explorer already owns
// the outer taskbar padding, so crop the export to the approved white tile
// itself. Retaining another transparent border here made the live 200%-DPI
// icon 4-9px smaller than neighbouring square icons. macOS continues to use
// the untouched approved 512px artwork.
const viewBox = [48, 48, 416, 416]
const approvedMarkLayout = 'x="40" y="40" width="432" height="432"'
const windowsMarkLayout = 'x="8" y="8" width="496" height="496"'
const layoutOccurrences = artworkText.split(approvedMarkLayout).length - 1
if (layoutOccurrences !== 3) throw new Error(`Approved application artwork layout changed (${layoutOccurrences} mark placements found)`)
const svg = artworkText
  .replace('<!-- GENERATED by apps/desktop-shell/scripts/build-brand-icons.mjs.', '<!-- GENERATED for Windows by apps/desktop-shell/scripts/build-windows-app-icon.mjs.')
  .replace('viewBox="0 0 512 512"', `viewBox="${viewBox.join(' ')}"`)
  .replaceAll(approvedMarkLayout, windowsMarkLayout)
const scratch = await mkdtemp(join(tmpdir(), 'xiaoshe-app-icon-export-'))
try {
  const svgPath = join(scratch, 'app-icon-win.svg')
  await writeFile(svgPath, svg, 'utf8')
  const frames = []
  const exports = { 'app-icon-win.svg': Buffer.from(svg) }
  // Rasterize the exact formal SVG once at high resolution, then derive every
  // native frame from that single master. This avoids renderer-to-renderer
  // geometry drift and keeps 16–40px taskbar edges crisp.
  const rasterMaster = sharp
    ? await sharp(Buffer.from(svg), { density: 288 }).resize(1024, 1024, { fit: 'fill' }).ensureAlpha().png({ palette: false }).toBuffer()
    : undefined
  for (const size of [16, 20, 24, 32, 40, 48, 64, 128, 256, 512]) {
    let png
    if (sharp) png = await sharp(rasterMaster).resize(size, size, { kernel: 'mitchell' }).ensureAlpha().png({ palette: false }).toBuffer()
    else {
      const path = join(scratch, `${size}.png`)
      const result = spawnSync('rsvg-convert', ['--width', String(size), '--height', String(size), '--format', 'png', '--output', path, svgPath], { stdio: 'inherit', windowsHide: true })
      if (result.error) throw result.error
      if (result.status !== 0) throw new Error(`rsvg-convert exited with ${result.status}`)
      png = await readFile(path)
    }
    if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || png.readUInt32BE(16) !== size || png.readUInt32BE(20) !== size) {
      throw new Error(`Invalid ${size}px rasterizer output`)
    }
    if (size <= 256) frames.push({ size, png })
    if (size >= 256) exports[`app-icon-win-${size}.png`] = png
  }
  // ICO frames contain independent PNG images so Explorer can select an exact
  // DPI size instead of repeatedly shrinking the 256px app image.
  const header = Buffer.alloc(6 + 16 * frames.length)
  header.writeUInt16LE(1, 2); header.writeUInt16LE(frames.length, 4)
  let offset = header.length
  frames.forEach(({ size, png }, index) => {
    const entry = 6 + index * 16
    header[entry] = size === 256 ? 0 : size; header[entry + 1] = header[entry]
    header.writeUInt16LE(1, entry + 4); header.writeUInt16LE(32, entry + 6)
    header.writeUInt32LE(png.length, entry + 8); header.writeUInt32LE(offset, entry + 12)
    offset += png.length
  })
  exports['app-icon-win.ico'] = Buffer.concat([header, ...frames.map(frame => frame.png)])
  await mkdir(output, { recursive: true })
  for (const [name, bytes] of Object.entries(exports)) await writeFile(join(output, name), bytes)
  await writeFile(join(output, 'app-icon-win.manifest.json'), `${JSON.stringify({
    schemaVersion: 2, source: 'runtime/xiaoshe-legacy/ui/assets/app-icon.svg', sourceSha256: sha(artwork),
    approvedPngSourceSha256: sha(source), formalSourceSha256: sha(formal), viewBox,
    windowsMarkLayout: { x: 8, y: 8, size: 496, scale: 496 / 432 },
    renderer: sharp ? `sharp ${sharp.versions.sharp} / librsvg ${sharp.versions.rsvg}` : 'rsvg-convert',
    outputs: Object.fromEntries(Object.entries(exports).map(([name, bytes]) => [name, sha(bytes)])),
  }, null, 2)}\n`, 'utf8')
} finally {
  await rm(scratch, { recursive: true, force: true })
}
process.stdout.write('Exported Windows application icons: exact formal mark, taskbar optical scale, 9 ICO sizes.\n')
